"""Normalized domain types the pipeline works with.

These are deliberately framework-agnostic (stdlib only) — no FastAPI, no Spotify JSON
shapes. Raw Spotify objects are normalized into `SourcedTrack` at the edge
(`pipeline/library.py`); everything downstream works with these.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import StrEnum
from typing import TYPE_CHECKING

if TYPE_CHECKING:  # numpy only needed for the centroid type hint (annotations are strings)
    import numpy as np


class Source(StrEnum):
    """Where a track came from — provenance only, NOT a weight.

    The occurrence weight is computed later in `pipeline/scoring.py` from `source` (+
    top-track `rank`); it is deliberately not a fixed source→number map. `added_at` is
    kept as provenance but no longer affects the weight (see scoring.py). There is no
    RECENTLY_PLAYED — recently-played is not fetched.
    """

    TOP_SHORT = "top_short"
    TOP_MEDIUM = "top_medium"
    TOP_LONG = "top_long"
    LIKED = "liked"
    PLAYLIST = "playlist"
    FALLBACK = "fallback"  # not from a player's library — generated by the embedding fallback


@dataclass
class SourceSelection:
    """A player's Profile Maker choices — the inputs to per-player extraction."""

    liked_count: int = 0
    playlist_ids: list[str] = field(default_factory=list)
    # Top tracks are fetched eagerly on connect (that's what makes Build profile fast), but
    # whether they end up in the library is the player's choice — unticking this gives a
    # playlists-only profile.
    include_top_tracks: bool = True


@dataclass
class SourcedTrack:
    """One track in a player's library, normalized and tagged with its source."""

    isrc: str | None
    spotify_id: str
    spotify_uri: str  # "spotify:track:..." — used for in-game playback
    name: str | None
    artist: str | None
    album_art: str | None
    year: int | None  # from album.release_date, for the game card
    source: Source
    added_at: datetime | None = None  # set for LIKED and PLAYLIST tracks; provenance only
    rank: int | None = None  # position within a top-tracks range (0 = strongest); else None


@dataclass
class PlayerLibrary:
    """Everything one player contributed, after extraction."""

    player_id: str
    username: str
    tracks: list[SourcedTrack] = field(default_factory=list)


@dataclass
class OwnerContribution:
    """One player's strongest occurrence of a matched song, with its precomputed weight.

    `weight` is the occurrence weight for this occurrence, computed once in `matching.py`
    (`scoring.occurrence_weight`) and reused by scoring and fair selection so it is never
    recomputed. `source`/`rank`/`added_at` are kept as provenance.
    """

    source: Source
    weight: float
    added_at: datetime | None = None
    rank: int | None = None


@dataclass
class MatchedSong:
    """A song after cross-player match detection: who has it, and how strongly."""

    isrc: str
    track: SourcedTrack  # representative metadata for display
    owners: dict[str, OwnerContribution] = field(default_factory=dict)  # player_id → contribution
    score: float = 0.0
    from_fallback: bool = False


@dataclass
class ClusterInfo:
    """One persisted taste cluster: its unit-norm centroid and the member song MBIDs."""

    index: int
    centroid: "np.ndarray"  # 128-d, unit-norm
    mbids: list[str] = field(default_factory=list)


@dataclass
class PlayerClusters:
    """A player's persisted clustering, computed once at Build-Profile time.

    `clusters` are the taste zones that cleared the min-size cut; `unclustered_mbids` are the
    player's other in-vocab songs (dismissed by the size cut) — kept, just not in any cluster.
    """

    player_id: str
    clusters: list[ClusterInfo] = field(default_factory=list)
    unclustered_mbids: list[str] = field(default_factory=list)
